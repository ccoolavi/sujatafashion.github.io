/* === LANGUAGE SWITCHING ENGINE === */
(function() {
  const DEFAULT_LANG = 'en';
  let currentLang = localStorage.getItem('sujata-lang') || DEFAULT_LANG;

  function applyLanguage(lang) {
    if (!TRANSLATIONS[lang]) { lang = DEFAULT_LANG; }
    currentLang = lang;
    localStorage.setItem('sujata-lang', lang);

    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = TRANSLATIONS[lang][key];
      if (text) {
        if (el.hasAttribute('placeholder')) {
          el.setAttribute('placeholder', text);
        } else {
          el.textContent = text;
        }
      }
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang === 'en' ? 'en' : (lang === 'hi' ? 'hi' : 'mr');

    // Update all language selects
    document.querySelectorAll('.lang-select').forEach(sel => {
      sel.value = lang;
    });

    // Dispatch custom event
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  // Apply on load
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyLanguage(currentLang));
  } else {
    applyLanguage(currentLang);
  }

  // Expose globally
  window.changeLanguage = applyLanguage;
  window.getCurrentLang = () => currentLang;
})()
